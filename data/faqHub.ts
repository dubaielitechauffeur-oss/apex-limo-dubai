/** Maps each service slug to the hub category its FAQs belong under. */
const SERVICE_CATEGORY_MAP: Record<string, string> = {
  "airport-transfers": "airport-transfers",
  "corporate-chauffeur": "corporate-travel",
  "luxury-chauffeur": "fleet",
  "vip-transportation": "vip-transportation",
  "event-transportation": "corporate-travel",
  "wedding-chauffeur": "wedding-chauffeurs",
};

/** Homepage FAQs, in data/faqs.ts order, mapped to their nearest hub category. */
const HOME_CATEGORY_ORDER = [
  "booking",
  "airport-transfers",
  "fleet",
  "booking",
  "safety",
  "general-questions",
];

/** Every FAQ on the site, localized and merged into one searchable,
 *  categorized hub. Resolved per-request rather than built once at module
 *  scope, since service/location/home FAQs are themselves per-locale. */
export function getAllFaqs(locale: Locale): PlainFaqHubEntry[] {
  const newFaqs: PlainFaqHubEntry[] = NEW_FAQS.map((faq) => ({
    id: faq.id,
    category: faq.category,
    question: pick(faq.question, locale),
    answer: pick(faq.answer, locale),
  }));

  const serviceFaqs: PlainFaqHubEntry[] = getAllServices(locale).flatMap((service) =>
    service.faqs.map((faq, index) => ({
      id: `service-${service.slug}-${index}`,
      category: SERVICE_CATEGORY_MAP[service.slug] ?? "general-questions",
      question: faq.question,
      answer: faq.answer,
    }))
  );

  const locationFaqs: PlainFaqHubEntry[] = getAllLocations(locale).flatMap((location) =>
    location.faqs.map((faq, index) => ({
      id: `location-${location.slug}-${index}`,
      category: "locations",
      question: faq.question,
      answer: faq.answer,
    }))
  );

  const homeFaqs: PlainFaqHubEntry[] = getFaqs(locale).map((faq, index) => ({
    id: `home-${index}`,
    category: HOME_CATEGORY_ORDER[index] ?? "general-questions",
    question: faq.question,
    answer: faq.answer,
  }));

  return [...newFaqs, ...homeFaqs, ...serviceFaqs, ...locationFaqs];
}
