function pick<T>(value: Localized<T>, locale: Locale): T {
  return value[locale] ?? value.en;
}

export interface PlainService {
  slug: string;
  name: string;
  tagline: string;
  heroSubtitle: string;
  shortDescription: string;
  longDescription: string[];
  ratingMetric: { value: string; label: string };
  benefits: string[];
  whyChoose: string[];
  faqs: { question: string; answer: string }[];
  image: { src: string; alt: string };
  tags: string[];
}

/** Resolves one service's Localized<T> fields to plain strings for the given locale. */
export function localizeService(service: Service, locale: Locale): PlainService {
  return {
    slug: service.slug,
    name: pick(service.name, locale),
    tagline: pick(service.tagline, locale),
    heroSubtitle: pick(service.heroSubtitle, locale),
    shortDescription: pick(service.shortDescription, locale),
    longDescription: pick(service.longDescription, locale),
    ratingMetric: {
      value: service.ratingMetric.value,
      label: pick(service.ratingMetric.label, locale),
    },
    benefits: pick(service.benefits, locale),
    whyChoose: pick(service.whyChoose, locale),
    faqs: service.faqs.map((faq) => ({
      question: pick(faq.question, locale),
      answer: pick(faq.answer, locale),
    })),
    image: { src: service.image.src, alt: pick(service.image.alt, locale) },
    tags: pick(service.tags, locale),
  };
}

export function getAllServices(locale: Locale): PlainService[] {
  return SERVICES.map((service) => localizeService(service, locale));
}

export function getServiceBySlug(slug: string, locale: Locale): PlainService | undefined {
  const service = SERVICES.find((s) => s.slug === slug);
  return service ? localizeService(service, locale) : undefined;
}
